-- 현재 재고 요약
SELECT 
    l.name AS warehouse_name,
    l.capacity,
    SUM(s.quantity) AS total_stock,
    l.capacity - SUM(s.quantity) AS remaining_capacity,
    ROUND((SUM(s.quantity) / l.capacity) * 100, 1) AS utilization_rate
FROM location l
JOIN stocks s ON l.id = s.location_id
WHERE l.type = 'WAREHOUSE'
GROUP BY l.id, l.name, l.capacity
ORDER BY utilization_rate DESC;

-- 물품별 전체 재고 현황
SELECT 
    w.name AS ware_name,
    SUM(s.quantity) AS total_quantity,
    COUNT(s.id) AS warehouse_count
FROM ware w
JOIN stocks s ON w.id = s.ware_id
JOIN location l ON s.location_id = l.id
WHERE l.type = 'WAREHOUSE'
GROUP BY w.id, w.name
ORDER BY total_quantity DESC;

-- 어제 완료된 작업 통계
SELECT 
    type,
    COUNT(*) AS task_count,
    SUM(quantity) AS total_quantity
FROM logistic_task
WHERE scheduled_date = '2025-06-22' AND status = 'COMPLETED'
GROUP BY type;

-- 작업자별 어제 업무량
SELECT 
    u.name AS worker_name,
    COUNT(t.id) AS task_count,
    SUM(t.quantity) AS total_quantity
FROM user_info u
JOIN logistic_task t ON u.id = t.worker_id
WHERE t.scheduled_date = '2025-06-22' AND t.status = 'COMPLETED'
GROUP BY u.id, u.name
ORDER BY task_count DESC;

-- 날짜별 작업 완료율 분석
SELECT
	scheduled_date,
	COUNT(*)                                                                                      as total_tasks,
	SUM(IF(final_status = 'COMPLETED', 1, 0))                                                     as completed,
	SUM(IF(final_status = 'COMPLETE_DELAYED', 1, 0))                                              as `delayed`,
    SUM(IF(final_status = 'FAILED', 1, 0))                                                        as failed,
    SUM(IF(final_status = 'CANCELLED', 1, 0))                                                     as cancelled,
    SUM(IF(final_status = 'EXPIRED', 1, 0))                                                       as expired,
    ROUND((SUM(IF(final_status IN ('COMPLETED', 'COMPLETE_DELAYED'), 1, 0)) / COUNT(*)) * 100, 1) as success_rate
FROM logistic_task_history
GROUP BY scheduled_date
ORDER BY scheduled_date DESC;

-- 작업자별 성과 분석 (최근 7일)
SELECT
	worker_name,
	COUNT(*)                                                                                      as total_tasks,
	SUM(IF(final_status = 'COMPLETED', 1, 0))                                                     as completed,
	SUM(IF(final_status = 'COMPLETE_DELAYED', 1, 0))                                              as `delayed`,
    SUM(IF(final_status = 'FAILED', 1, 0))                                                        as failed,
    SUM(IF(final_status = 'EXPIRED', 1, 0))                                                       as expired,
    ROUND((SUM(IF(final_status IN ('COMPLETED', 'COMPLETE_DELAYED'), 1, 0)) / COUNT(*)) * 100, 1) as success_rate,
    ROUND(AVG(IF(atd IS NOT NULL AND etd IS NOT NULL, TIMESTAMPDIFF(MINUTE, etd, atd), NULL)), 2) as avg_start_delay_minutes
FROM logistic_task_history
WHERE scheduled_date >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
GROUP BY worker_id, worker_name
ORDER BY success_rate DESC, total_tasks DESC;

-- 물품별 이동 분석
SELECT
	ware_name,
	type,
	COUNT(*)                                                                                      as total_movements,
	SUM(quantity)                                                                                 as total_quantity,
	AVG(quantity)                                                                                 as avg_quantity,
	SUM(IF(final_status IN ('COMPLETED', 'COMPLETE_DELAYED'), 1, 0))                              as successful_movements,
	ROUND((SUM(IF(final_status IN ('COMPLETED', 'COMPLETE_DELAYED'), 1, 0)) / COUNT(*)) * 100, 1) as success_rate
FROM logistic_task_history
WHERE scheduled_date >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
GROUP BY ware_id, ware_name, type
ORDER BY total_quantity DESC;

-- 어제의 미완료 작업 분석 (계획 수립 참고용)
SELECT
	type,
	ware_name,
	from_location_name,
	to_location_name,
	quantity,
	final_status,
	etd,
	CASE final_status
		WHEN 'EXPIRED' THEN '시간내 미완료'
		WHEN 'FAILED' THEN '작업 중 실패'
		WHEN 'CANCELLED' THEN '작업 취소'
		END as issue_description
FROM logistic_task_history
WHERE scheduled_date = DATE_SUB(CURDATE(), INTERVAL 1 DAY)
  AND final_status IN ('EXPIRED', 'FAILED', 'CANCELLED')
ORDER BY type, etd;

