	from_location_name as location_name,
	'OUTBOUND' as direction,
	COUNT(*) as task_count,
	SUM(quantity) as total_quantity
FROM logistic_task_history
WHERE scheduled_date >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
GROUP BY from_location_id, from_location_name

UNION ALL

SELECT
	to_location_name as location_name,
	'INBOUND' as direction,
	COUNT(*) as task_count,
	SUM(quantity) as total_quantity
FROM logistic_task_history
WHERE scheduled_date >= DATE_SUB(CURDATE(), INTERVAL 7 DAY)
GROUP BY to_location_id, to_location_name
ORDER BY location_name, direction;

